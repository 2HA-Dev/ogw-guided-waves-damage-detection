"""Step 5: C++ export with Eclipse Aidge 0.10.1 (.venv-aidge environment).

For each configuration (ONNX model, dtype, data format), the C++ code is
generated with aidge_core.export_utils.export, a test program (harness) is
compiled against the generated model_forward function, run on 64 test
measurements and 128 calibration measurements, and compared with ONNX Runtime.
Failing configurations are kept: they are part of the findings.

Prerequisite: .venv/bin/python step05_aidge_export/prepare_data.py (data and folded ONNX models).
Run (from the repository root): .venv-aidge/bin/python step05_aidge_export/export_aidge.py
"""
