def pad(A, name):
    """Variants "_16": input padded with zero channels up to 80 (Step 9)."""
    return np.concatenate([A, np.zeros((len(A), 80 - A.shape[1], A.shape[2]), A.dtype)], 1) if "_16" in name else A
NT = len(D["test"])
SIZES = {"float": 4, "int8_t": 1, "uint8_t": 1, "int16_t": 2, "int32_t": 4, "int64_t": 8, "bool": 1}

